namespace PrintFlow.Domain;

/// <summary>
/// مدى الصفحات المطلوب طباعته من كل مستند — "من صفحة ٥ لصفحة ٢٠".
///
/// ═══ ليه مش "حذف الصفحات" اللي موجود أصلًا ═══
///
/// حذف الصفحات بيغيّر المستند نفسه قبل الطباعة: بيشيل الصفحات ويعيد
/// الترقيم من ١. فلو المستخدم عايز يطبع من ٥ لـ ٢٠ وحذف ١-٤، الصفحة
/// اللي كانت رقم ٥ بتطلع مكتوب عليها ١ — وده غلط في ملزمة أو كتاب.
///
/// المدى ده بيشتغل **وقت الطباعة بس**: المستند مابيتلمسش، والترقيم
/// بيفضل زي ما هو، وبنقول للطابعة تطلّع الصفحات دي بس.
///
/// ═══ الصفر معناه "مفيش حد" ═══
///
/// صفر في <c>from</c> = من أول المستند. صفر في <c>to</c> = لآخره.
/// اخترنا الصفر بدل null عشان الخانة في الواجهة تفضل رقم عادي، والـ
/// Preset يتحفظ ويترجع من غير أي حالة خاصة.
///
/// حساب خالص على أرقام — متختبر من غير طابعة ولا ملف.
/// </summary>
public static class PageRange
{
    /// <summary>
    /// هل المستخدم طلب جزء من المستند فعلًا، ولا سايبها على الكل؟
    ///
    /// دي اللي بتقرر يظهر التحذير الأحمر في الواجهة ولا لأ. المدى
    /// بيتحفظ في الإعدادات، فمن غير التحذير ده حد ممكن يظبطه النهاردة
    /// ويفضل كل أوردر بعد كده بيتقص وهو مش واخد باله.
    /// </summary>
    public static bool IsSubset(int from, int to) => from > 1 || to > 0;

    /// <summary>
    /// بيحوّل اللي المستخدم كتبه لأول وآخر صفحة فعليين.
    ///
    /// بيرجّع <c>(0, 0)</c> لو مفيش مدى نقدر نصدّقه — يعني اطبع المستند
    /// كله. ده بيحصل لما عدد الصفحات مجهول ومفيش "لحد صفحة" مكتوبة،
    /// أو لما المستخدم يكتب مدى مقلوب (من ٢٠ لـ ٥).
    /// </summary>
    /// <param name="pageCount">عدد صفحات المستند. صفر = مجهول.</param>
    public static (int First, int Last) Resolve(int from, int to, int pageCount)
    {
        int first = from > 0 ? from : 1;
        int last = to > 0 ? to : pageCount;

        // مفيش آخر صفحة نعرفها → مانقدرش نكتب مدى. الطباعة كاملة أأمن
        // من إننا نخمّن ونطبع ناقص.
        if (last <= 0)
        {
            return (0, 0);
        }

        // المستند ٢٠ صفحة والمستخدم كتب "لحد ٢٠٠": بنقصّها على ٢٠ بدل
        // ما نبعت رقم الطابعة متعرفهوش.
        //
        // ⚠ بنقص الآخر بس. أول واحدة كتبتها هنا كانت بتقص البداية كمان
        // على النهاية (Math.Min(first, last))، وده كان بيحوّل مدى مقلوب
        // زي "من ٢٠ لـ ٥" لـ "5-5" — يعني المستخدم يغلط ويطبع صفحة
        // واحدة من غير ما حد يقوله. التست هو اللي مسكها.
        if (pageCount > 0)
        {
            last = Math.Min(last, pageCount);
        }

        // مدى مقلوب (من ٢٠ لـ ٥) = المستخدم غلط. بنطبع الكل بدل ما نطبع
        // ولا حاجة ويقعد يستنى ورق مش جاي.
        return last < first ? (0, 0) : (first, last);
    }
        /// <summary>
    /// عدد الصفحات اللي بتطلع فعلًا من **نسخة واحدة** بعد حساب المدى.
    ///
    /// ═══ ليه لازم تبقى في مكان واحد ═══
    ///
    /// الحسبة دي كانت مكتوبة في <c>PrintJob.PagesPerCopy</c> بس. البار
    /// والموزّع كانوا بياخدوا عدد صفحات المستند الخام — فالبرنامج كان
    /// بيقول «٢٤ صفحة» على أوردر طلّع منه ١٦ ورقة بس.
    ///
    /// ⚠ والمدى بيتقص على طول كل مستند لوحده: «من ٥ لـ ٢٠» في مستند
    /// ٢٤ صفحة = ١٦، وفي مستند ١٠ صفحات = ٦. يعني نفس المدى بيدي أرقام
    /// مختلفة — وده اللي كان بيبوّظ أوزان التوزيع لما الملفات أطوالها
    /// مختلفة.
    ///
    /// بيرجّع <paramref name="pageCount"/> زي ما هو لما مفيش مدى نصدّقه.
    /// </summary>
    public static int CountIn(int from, int to, int pageCount)
    {
        var (first, last) = Resolve(from, to, pageCount);

        return last >= first && first > 0 ? last - first + 1 : pageCount;
    }

    /// <summary>
    /// سطر عربي للواجهة يقول اللي هيحصل بالظبط — مش تعليمات.
    /// بيرجّع "" لما المستند بيتطبع كامل.
    /// </summary>
    public static string Describe(int from, int to)
    {
        if (!IsSubset(from, to))
        {
            return "";
        }

        if (from > 0 && to > 0 && from > to)
        {
            // من غير نجوم ماركداون — السطر ده بيتعرض نص خام في الواجهة،
            // فالنجوم كانت بتظهر للمستخدم زي ما هي.
            return $"⚠ المدى مقلوب: البداية ({from}) أكبر من النهاية ({to}) — " +
                   "المستند هيتطبع «كامل» لحد ما تصلّحه.";
        }

        string where = (from > 1, to > 0) switch
        {
            (true, true) => $"من صفحة {from} لصفحة {to}",
            (true, false) => $"من صفحة {from} لآخر المستند",
            _ => $"من أول المستند لصفحة {to}"
        };

        return $"⚠ مدى الصفحات شغّال: {where}. أي صفحة برّه المدى ده مش هتتطبع من أي ملف.";
    }
}