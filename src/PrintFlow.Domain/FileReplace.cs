namespace PrintFlow.Domain;

/// <summary>
/// قواعد إعادة المحاولة لما استبدال ملف يفشل.
///
/// ═══ ليه ده موجود ═══
///
/// حفظ الإعدادات بيكتب في ملف مؤقت وبعدين ينقله فوق الملف الأصلي. النقل
/// ده (<c>File.Move(overwrite: true)</c>) بيستخدم <c>MoveFileEx</c> على
/// ويندوز — ودي **بتفشل لو الملف الهدف مفتوح** عند أي حد تاني في نفس
/// اللحظة، حتى لو هو بيقرا بس.
///
/// وده مش نادر خالص على جهاز ويندوز حقيقي:
///
///   • مضاد الفيروسات بيفتح الملف يفحصه بعد ما اتكتب
///   • Windows Search بيفهرسه
///   • OneDrive بيزامنه لو المجلد متزامن
///   • البرنامج نفسه مفتوح مرتين وبيحفظ في نفس اللحظة
///
/// كل دول بيمسكوا الملف **لأجزاء من الثانية** وبعدين يسيبوه. فالحل إننا
/// نعيد المحاولة شوية بدل ما نفشل من أول مرة.
///
/// ═══ نقطة مهمة: نفس الاستثناء، معنى مختلف ═══
///
/// النقل الفاشل ده بيرمي <c>UnauthorizedAccessException</c> — نفس نوع
/// الاستثناء اللي في <see cref="FileClaim"/> قلنا عليه إنه **مابيتحلش
/// بالانتظار** وإن إعادة المحاولة فيه مضيعة وقت.
///
/// الكلام ده لسه صح هناك وغلط هنا، والفرق في المصدر:
///
///   • هناك: ملف عمله حساب SYSTEM والمستخدم مش مالكه → قرار دائم في
///     نظام الصلاحيات، الانتظار مش هيغيّره.
///   • هنا: الملف بتاعنا وصلاحياتنا عليه تمام، بس **مشغول دلوقتي**.
///     ويندوز بيقول عن ده Access Denied كمان — وده بيعدّي بعد لحظات.
///
/// عشان كده الأرقام هنا صغيرة: ٨ محاولات بتصاعد من ٥ مللي لـ ١٦٠،
/// مجموعها أقل من تلت ثانية. لو المشكلة صلاحيات حقيقية، بنخسر التلت
/// ثانية دي مرة واحدة وبعدين بنقول الحقيقة — وده مقبول لحفظ إعدادات
/// بيحصل كل شوية مش كل لحظة.
/// </summary>
public static class FileReplace
{
    /// <summary>كام محاولة إجمالًا (بما فيهم الأولى).</summary>
    public const int Attempts = 8;

    /// <summary>
    /// نستنى كام مللي قبل المحاولة رقم <paramref name="attempt"/>
    /// (الترقيم من صفر — المحاولة الأولى مالهاش انتظار).
    ///
    /// التصاعد مقصود: أغلب الاصطدامات بتتحل في أول ٥-٢٠ مللي، فمانستناش
    /// كتير على الفاضي. واللي بياخد وقت (مضاد فيروسات بيفحص ملف كبير)
    /// بياخد فرصته في المحاولات الأخيرة.
    /// </summary>
    public static int DelayMilliseconds(int attempt) => attempt switch
    {
        <= 0 => 0,
        1 => 5,
        2 => 10,
        3 => 20,
        4 => 40,
        5 => 80,
        _ => 160
    };

    /// <summary>مجموع الانتظار لو المحاولات كلها فشلت.</summary>
    public static int TotalBudgetMilliseconds
    {
        get
        {
            int total = 0;

            for (int attempt = 0; attempt < Attempts; attempt++)
            {
                total += DelayMilliseconds(attempt);
            }

            return total;
        }
    }

    /// <summary>
    /// الاستثناء ده يستاهل إعادة محاولة؟
    ///
    /// الاتنين دول بس: <c>UnauthorizedAccessException</c> (الهدف مشغول أو
    /// ممنوع) و<c>IOException</c> (مقفول). أي حاجة تانية — مسار غلط، قرص
    /// مش موجود، تسلسل بايظ — إعادة المحاولة فيها مضيعة وقت خالصة.
    /// </summary>
    public static bool WorthRetrying(Exception? exception)
        => exception is UnauthorizedAccessException or IOException;

    /// <summary>دي آخر محاولة؟ (يعني مفيش فايدة من الانتظار بعدها).</summary>
    public static bool IsLastAttempt(int attempt) => attempt >= Attempts - 1;
}
