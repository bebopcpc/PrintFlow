namespace PrintFlow.Domain;

/// <summary>
/// بتعلّم على إعداد هو **توصيلة** مش تفضيل مظهر.
///
/// ═══ ليه ده موجود ═══
///
/// زرار "استعادة الإعدادات الافتراضية" بيمشي بالـ Reflection على كل خصايص
/// <see cref="AppSettings"/> — وده مقصود، عشان أي خاصية جديدة تتضاف بكرة
/// تبقى مغطّاة من غير ما حد يفتكر يضيفها في لستة.
///
/// بس الشمول ده كان بيعمل حاجة وحشة: بيقفل الاستقبال.
///
/// الفرق بين النوعين مهم:
///
///   • تفضيل مظهر (لون الترقيم، حجم العلامة) → لو رجع للافتراضي، المستخدم
///     **بيشوف** الفرق على طول ويرجّعه.
///
///   • توصيلة (الاستقبال، المجلد المراقَب) → لو اتقفلت، مفيش أي حاجة تبان.
///     البرنامج بيفضل شكله سليم، والشغل اللي جاي من بره بيروح في الهوا
///     ومحدش ياخد باله غير لما حد يسأل "فين الملف اللي بعتّهولك؟"
///
/// فالخصايص المعلّمة بالسمة دي بيسيبها زرار الافتراضي زي ما هي.
/// المستخدم اللي عايز يقفل الاستقبال بيشيل العلامة من المربع بنفسه —
/// دي خطوة واحدة وواضحة، مش أثر جانبي لزرار تاني.
///
/// ملحوظة: التست <c>Restoring_Defaults_Resets_Every_Single_Property</c>
/// لسه بيمشي بالـ Reflection على الباقي كله، فالضمانة القديمة ما ضاعتش —
/// بس بقى فيه استثناء **مكتوب ومقصود** بدل استثناء منسي.
/// </summary>
[AttributeUsage(AttributeTargets.Property)]
public sealed class ConnectionSettingAttribute : Attribute
{
}
