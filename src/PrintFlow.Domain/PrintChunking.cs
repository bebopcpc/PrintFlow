namespace PrintFlow.Domain;

/// <summary>
/// بيقسّم النسخ على أكتر من جوب بدل ما يبعتها كلها في أمر واحد.
///
/// ═══ العطل اللي الملف ده اتعمل بسببه ═══
///
/// لما صلّحنا الترتيب (Collation) بقينا نبعت المدى مكرر: عشر نسخ من مستند
/// ١٨٠ صفحة بقت <c>1-180</c> مكتوبة عشر مرات = **١٨٠٠ صفحة في جوب واحد**.
/// الترتيب طلع مظبوط، بس المطبعة وقعت: الطابعة بتقف حوالي الورقة ٤٠ ومش
/// بتكمّل. جوب بالحجم ده بيملا السبولر وذاكرة الطابعة وبيخنقها.
///
/// اللي كان بيحصل قبل الإصلاح ماكانش بيعمل كده لأن <c>10x</c> كان بيسيب
/// الدرايفر يكرّر ١٨٠ صفحة عشر مرات — كل نسخة شغل مستقل عنده.
///
/// ═══ الحل ═══
///
/// بنرجّع نفس الفكرة بس **إحنا اللي ماسكينها**: بدل جوب واحد ١٨٠٠ صفحة،
/// عشر جوبات كل واحد نسخة كاملة (١٨٠ صفحة). الطابعة بتخلص جوب وتفضّي
/// نفسها وتبدأ اللي بعده.
///
/// ═══ ليه الترتيب مابيضيعش ═══
///
/// كل دفعة **نسخ كاملة**، مش نص نسخة. والجوبات بتتبعت واحدة ورا التانية
/// (بننتظر كل واحدة تخلص قبل ما نبعت اللي بعدها)، وطابور الطابعة بيطبع
/// بالترتيب. يعني النتيجة على الورق: نسخة كاملة ورا نسخة كاملة — بالظبط
/// زي جوب واحد كبير.
///
/// ⚠ **مابنقسّمش نسخة على جوبين أبدًا.** لو عملنا كده، الطباعة على وجهين
/// كانت هتلزق آخر صفحة من نسخة بأول صفحة من اللي بعدها على نفس الورقة.
///
/// حساب خالص على أرقام — متختبر من غير طابعة ولا ملف.
/// </summary>
public static class PrintChunking
{
    /// <summary>
    /// أكبر عدد صفحات نسمح بيه في الجوب الواحد.
    ///
    /// مش رقم مقدّس: هو حل وسط بين «جوب كبير بيخنق الطابعة» و«جوبات كتير
    /// أوي بتبطّئ الشغل» (كل جوب = تشغيل بروسيس سوماترا من جديد).
    /// ١٨٠ صفحة عدّت، و١٨٠٠ وقعت — فالحد هنا فوق النسخة الواحدة العادية
    /// وتحت الحجم اللي وقع بكتير.
    /// </summary>
    public const int MaxPagesPerJob = 300;

    /// <summary>
    /// بيرجّع عدد النسخ في كل دفعة، بالترتيب.
    ///
    /// دايمًا بيرجّع عنصر واحد على الأقل، ومجموع العناصر = <paramref name="copies"/>
    /// بالظبط — مفيش نسخة بتضيع ولا بتتكرر.
    /// </summary>
    /// <param name="copies">عدد النسخ المطلوبة من المكنة دي.</param>
    /// <param name="pagesPerCopy">صفحات النسخة الواحدة. صفر = مش عارفين.</param>
    public static IReadOnlyList<int> Split(int copies, int pagesPerCopy)
    {
        if (copies <= 1)
        {
            return [copies];
        }

        // مش عارفين المستند كام صفحة؟ يبقى مانقدرش نحسب. بنبعت زي ما إحنا
        // بنعمل دلوقتي — التخمين هنا ممكن يقسّم أوردر صغير لعشرين جوب
        // من غير أي داعي.
        if (pagesPerCopy <= 0)
        {
            return [copies];
        }

        // نسخة واحدة على الأقل في كل دفعة، حتى لو النسخة لوحدها أكبر من
        // الحد. مستند ٥٠٠ صفحة مالوش حل تاني — وعلى الأقل مش هنبعت
        // خمس آلاف صفحة مرة واحدة.
        int perChunk = Math.Max(1, MaxPagesPerJob / pagesPerCopy);

        if (perChunk >= copies)
        {
            return [copies];
        }

        var chunks = new List<int>((copies / perChunk) + 1);

        for (int left = copies; left > 0; left -= perChunk)
        {
            chunks.Add(Math.Min(perChunk, left));
        }

        return chunks;
    }
}