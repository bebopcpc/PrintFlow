namespace PrintFlow.Domain;

/// <summary>
/// قاعدة واحدة بس: الكتيّب لازمه طباعة على الوجهين.
///
/// ═══ ليه دي محتاجة كلاس لوحدها ═══
///
/// الكتيّب مش خيار شكلي — هو إعادة ترتيب للصفحات مبنية على افتراض
/// إن الورقة هتتطبع من الوجهين وتتطوي من النص. <see cref="BookletImposition"/>
/// بيرتّب ٨ صفحات كده: [٨،١] [٢،٧] [٦،٣] [٤،٥] — أربع أوجه، كل اتنين
/// منهم قدام وضهر ورقة واحدة.
///
/// لو الطباعة على وجه واحد، الأربعة بيطلعوا على أربع ورقات منفصلة.
/// الترتيب نفسه صح، بس الورق ضِعف اللازم ونُصّه فاضي، والطي مش بيدّي
/// كتيّب — بيدّي كوم ورق. يعني أوردر رايح في الزبالة بالكامل.
///
/// ═══ ليه تحذير مش منع ═══
///
/// جرّبنا نفكّر إن البرنامج يشغّل الوجهين لوحده لما الكتيّب يتفتح.
/// رفضناها لسببين:
///
///   • في مطابع بتعمل الوجهين بالإيد — بتطبع وجه، تقلب الورق، تعيد.
///     المكن الرخيصة كتير مابتعرفش تقلب لوحدها. اللي بيعمل كده بيقفل
///     خيار الوجهين عن قصد، والبرنامج لو فتحه لوحده هيبقى بيخانقه.
///   • ونفس المبدأ اللي ماشي في البرنامج كله: البرنامج يقول اللي
///     هيحصل بوضوح، والقرار يفضل للي واقف على المكنة.
///
/// فالسطر ده بيتكتب بالأحمر تحت خيار الكتيّب على طول — نفس أسلوب
/// تحذير مدى الصفحات، وهو مجرّب وشغّال.
///
/// ═══ ليه هنا مش في الـ ViewModel ═══
///
/// عشان يتختبر من غير واجهة ولا طابعة، وعشان يفضل مصدر واحد للقرار
/// ده لو احتجناه في مكان تاني بعدين (زرار الطباعة، اللوج، تقرير).
///
/// حساب خالص على قيمتين bool.
/// </summary>
public static class BookletRules
{
    /// <summary>
    /// الكتيّب شغّال والوجهين مقفول؟ ده الشرط اللي بيظهّر السطر الأحمر.
    /// </summary>
    public static bool NeedsDuplex(bool bookletMode, bool duplex) => bookletMode && !duplex;

    /// <summary>
    /// نفس السؤال بس من الإعدادات اللي الطباعة نفسها هتقراها.
    ///
    /// ⚠ الواجهة لازم تنده دي — مش تعيد كتابة الشرط عندها. أول مرة
    /// كتبنا شرط زي ده مرتين (في <c>SlideRequest.IsPassThrough</c>)،
    /// الاتنين اختلفوا، والبرنامج فضل يقول إنه بيعمل حاجة وهو مش
    /// بيعملها.
    /// </summary>
    public static bool NeedsDuplex(PrintSettings settings)
    {
        ArgumentNullException.ThrowIfNull(settings);

        return NeedsDuplex(settings.BookletMode, settings.Duplex);
    }

    /// <summary>
    /// سطر عربي للواجهة يقول اللي هيحصل بالظبط. بيرجّع "" لما مفيش مشكلة.
    /// </summary>
    public static string Describe(bool bookletMode, bool duplex)
    {
        if (!NeedsDuplex(bookletMode, duplex))
        {
            return "";
        }

        // من غير نجوم ماركداون — السطر ده بيتعرض نص خام في الواجهة،
        // فالنجوم كانت بتظهر للمستخدم زي ما هي.
        return "⚠ الكتيّب شغّال والطباعة على وجه واحد. الترتيب هيطلع صح بس " +
               "كل ورقة هيتطبع وش واحد بس منها — الطي مش هيدّي كتيّب، والورق " +
               "هيتصرف ضِعف اللازم. شغّل «الطباعة على الوجهين» من خيارات الطباعة.";
    }

    /// <inheritdoc cref="Describe(bool, bool)"/>
    public static string Describe(PrintSettings settings)
    {
        ArgumentNullException.ThrowIfNull(settings);

        return Describe(settings.BookletMode, settings.Duplex);
    }
}
