namespace PrintFlow.Domain;

/// <summary>
/// بيقول بالظبط **أنهي إعدادات هتضيع** لو المستخدم ضغط «طباعة الآن» من
/// غير ما يعمل معالجة.
///
/// ═══ العطل اللي الملف ده اتعمل بسببه ═══
///
/// التحذير القديم كان جملة ثابتة مكتوبة بالإيد:
///
///   «الملفات هتتبعت زي ما هي — من غير دمج ولا بوكليت ولا علامة مائية
///    ولا ترقيم.»
///
/// أربع حاجات. والحقيقة **تمانية** — الجملة كانت ناسية: حذف الصفحات،
/// مقياس الصفحة، تجميع الشرائح، والنص المخصص.
///
/// ووقعت فعلًا: مستخدم ظبط مقياس الصفحة ٩٢٪ عشان الطابعة بتقص الحواف،
/// ضغط «طباعة الآن»، وقرا تحذير **مقياس الصفحة مش مذكور فيه** — فاستنتج
/// إنه اتطبّق. الورق طلع من غير هامش وهو مش فاهم ليه.
///
/// التحذير اللي بيقول أربعة من تمانية أسوأ من تحذير مش موجود: اللي مش
/// موجود بيخلّي الناس تشك، واللي ناقص بيخلّيها تطمن غلط.
///
/// ═══ ليه بنسأل نفس المصادر مش قايمة جديدة ═══
///
/// العلامة المائية والنص المخصص بيتسألوا من <c>WatermarkStyle.From</c> و
/// <c>OverlayTextStyle.From</c> — **نفس الدوال اللي السلسلة نفسها
/// بتستخدمها**. لو قايمة تانية اتكتبت هنا بالإيد، أول ما حد يغيّر شرط في
/// السلسلة، التحذير هيكدب من تاني ومحدش هيلاحظ.
///
/// حساب خالص على الإعدادات — متختبر من غير طابعة ولا ملف.
/// </summary>
public static class SkippedProcessing
{
    /// <summary>
    /// أسامي الإعدادات اللي المستخدم مشغّلها **وهتضيع** في الطباعة الخام.
    /// لستة فاضية = مفيش حاجة هتضيع.
    /// </summary>
    /// <param name="fileCount">عدد الملفات المحمّلة — الدمج مالوش معنى في ملف واحد.</param>
    public static IReadOnlyList<string> ListFor(PrintSettings print, AppSettings app, int fileCount)
    {
        ArgumentNullException.ThrowIfNull(print);
        ArgumentNullException.ThrowIfNull(app);

        var lost = new List<string>();

        // الدمج بيتقال بس لما يبقى ليه معنى. «الدمج مش هيتطبق» على ملف
        // واحد كلام صح ومالوش أي لازمة — والتحذير اللي فيه حشو بيتقرا أقل.
        if (print.MergeFiles && fileCount > 1)
        {
            lost.Add($"دمج الـ {fileCount} ملف في مستند واحد");
        }

        if (print.BookletMode)
        {
            lost.Add("طباعة بوكليت");
        }

        if (print.SlidesPerSheet > 1)
        {
            lost.Add($"تجميع {print.SlidesPerSheet} شرائح على الورقة");
        }

        if (print.DeletePages && !string.IsNullOrWhiteSpace(print.PagesToDelete))
        {
            lost.Add($"حذف الصفحات ({print.PagesToDelete.Trim()})");
        }

        if (print.NumberPagesPerFile)
        {
            lost.Add("ترقيم الصفحات");
        }

        // نفس الدالة اللي السلسلة بتقرر بيها — مش شرط متكرر بالإيد
        if (WatermarkStyle.From(app) is not null)
        {
            lost.Add("العلامة المائية");
        }

        if (OverlayTextStyle.From(app) is not null)
        {
            lost.Add("النص المخصص");
        }

        // ⚠ ده اللي كان ناقص وضيّع ورق حقيقي
        if (!PageScaling.IsIdentity(print.ScalePercent))
        {
            lost.Add($"مقياس الصفحة {PageScaling.Clamp(print.ScalePercent)}%");
        }

        return lost;
    }

    /// <summary>
    /// السطر اللي بيتكتب في النتائج. بيقول الأسامي بالظبط، مش قايمة عامة.
    ///
    /// ولما مفيش حاجة هتضيع بيقول كده صراحة — «مفيش حاجة تضيع» معلومة
    /// مفيدة لواحد على وشك يضغط طباعة على أوردر عميل.
    ///
    /// ⚠ **من غير نجوم ماركداون في النص المعروض.**
    ///
    /// السطر ده بيتعرض نص خام في شاشة النتائج — مفيش حاجة بتفسّر
    /// الماركداون. فالنجوم كانت بتوصل للمستخدم زي ما هي:
    /// «الإعدادات دي **مش هتتطبق**». القوسين العربيين بيعملوا نفس
    /// التمييز وبيتقروا صح.
    ///
    /// (النجوم في تعليقات الـ /// فوق مالهاش مشكلة — دي للمبرمج،
    ///  ومحدش بيعرضها للمستخدم.)
    /// </summary>
    public static string Describe(PrintSettings print, AppSettings app, int fileCount)
    {
        var lost = ListFor(print, app, fileCount);

        if (lost.Count == 0)
        {
            return "[طباعة مباشرة] الملفات هتتبعت زي ما هي — ومفيش أي إعداد معالجة شغّال، " +
                   "فمفيش حاجة هتضيع.";
        }

        return $"⚠ [طباعة مباشرة] الإعدادات دي «مش هتتطبق»: {string.Join("، ", lost)}. " +
               "لو عايزها، اضغط «بدء معالجة الملفات» الأول.";
    }
}
