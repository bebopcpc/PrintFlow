using PrintFlow.Domain;

namespace PrintFlow.Application;

/// <summary>
/// بيقرا طابور طابعة واحدة من النظام.
///
/// اتفصل في واجهة عشان <c>Presentation</c> يقدر يستخدمه من غير ما يعرف
/// حاجة عن WMI ولا عن ويندوز أصلًا — نفس القاعدة اللي ماشيين عليها في كل
/// حاجة بتلمس النظام.
/// </summary>
public interface IPrinterQueue
{
    /// <summary>
    /// حالة الطابور دلوقتي. **عمرها ما ترمي** — لو مقدرناش نقرا،
    /// بترجّع <see cref="PrinterQueueState.Idle"/>.
    ///
    /// السبب: دي بتتنده كل تانيتين وسط أوردر شغّال. استثناء من قراءة
    /// معلومة للعرض مايصحّش يوقف طباعة.
    /// </summary>
    PrinterQueueState Read(string printerName);
    
    /// <summary>
    /// بيشيل كل جوبات الطابعة دي من الطابور، وبيرجّع عدد اللي اتشال.
    ///
    /// ═══ ليه دي موجودة ═══
    ///
    /// «إيقاف فوري» كان بيوقف **البرنامج** مش **الورق**: بنقتل بروسيسات
    /// الطباعة، بس اللي وصل طابور ويندوز خلاص بيفضل ماشي لآخره. في مطبعة
    /// معناها إنك تكتشف غلطة في الملف، تدوس إيقاف، وتقعد تتفرّج على مئات
    /// الورقات الغلط وهي بتخرج من خمس مكن.
    ///
    /// ⚠ ودي بتشيل من **طابور ويندوز** بس. الورق اللي وصل ذاكرة الطابعة
    /// نفسها هيطلع مهما عملنا — مفيش حاجة في الكمبيوتر توقفه.
    ///
    /// **عمرها ما ترمي** — بترجّع صفر لو مقدرناش.
    /// </summary>
    int CancelAll(string printerName);
}