namespace PrintFlow.Application;

/// <summary>
/// حالة مكنة واحدة في لحظة معيّنة، من زاوية سؤال واحد:
/// **أدّيها القطعة اللي بعدها ولا لأ؟**
///
/// وفيه تلات إجابات مش اتنين:
///
///   • <see cref="Fine"/> — آه، خدي.
///   • <see cref="Busy"/> — لأ **دلوقتي**، لسه بتخلّص اللي معاها. دي مش
///     مشكلة، دي الوضع الطبيعي لمكنة شغالة.
///   • <see cref="Stopped"/> — لأ، فيها عطل. الورق خلص، مفصولة، موقوفة.
///
/// الفرق بين الاتنين الأخيرين مش شكلي: "مشغولة" مابتتكتبش في اللوج
/// ومابتحسبش في مهلة الاستسلام (المكنة شغالة فعلًا وهتفضى)، و"واقفة"
/// بتتكتب مرة واحدة وبتبدأ العد.
/// </summary>
/// <param name="CanTakeWork">تقدر تاخد قطعة جديدة دلوقتي.</param>
/// <param name="IsFault">اللي مانعها عطل محتاج يد بشرية، مش مجرد شغل.</param>
/// <param name="Reason">السبب العربي — null لو كل حاجة تمام.</param>
public sealed record PrinterHealth(bool CanTakeWork, bool IsFault, string? Reason)
{
    public static readonly PrinterHealth Fine = new(true, false, null);

    /// <summary>شغالة وطابورها مليان — استنى وماتقولش حاجة.</summary>
    public static PrinterHealth Busy(string reason) => new(false, false, reason);

    /// <summary>فيها عطل — قول السبب وابدأ العد.</summary>
    public static PrinterHealth Stopped(string reason) => new(false, true, reason);
}

/// <summary>
/// بيسأل الطابعة عن حالتها قبل ما ندّيها شغل جديد.
///
/// ═══ ليه ده أهم حتة في التوزيع ═══
///
/// الحدس بيقول: المكنة اللي وقعت هتفشّل الطباعة فإحنا هنعرف. الحقيقة عكس
/// كده تمامًا على ويندوز.
///
/// في الوضع الافتراضي (spool ثم اطبع)، السبولر بيقبل الجوب **حتى لو الورق
/// خلص**. الجوب بيقعد في الطابور، وSumatraPDF بيخرج بكود صفر، وإحنا بنكتب
/// "[نجاح] اتسلّمت لطابور" — وده صحيح حرفيًا ومضلّل عمليًا.
///
/// وده بيعمل مشكلتين مختلفتين:
///
///   ١) **العطل مابيبانش.** المكنة اللي الورق خلص منها بتفضل تقبل جوبات
///      وتكوّمها، والمكن التانية بتخلص وتقف. الأوردر بيستنى أبطأ حاجة في
///      الأوضة.
///
///   ٢) **التوزيع بيتلغي من أصله.** التسليم للسبولر بيخلص في ثواني بغض
///      النظر عن الطباعة الحقيقية. من غير كابح، أول مكنة تلحق بتشفط
///      الشغل كله في طابور ويندوز بتاعها في أول عشر ثواني، وبعد كده مفيش
///      حاجة فاضلة تتوزّع لما مكنة تقع. التوزيع بيبقى **على الورق بس**.
///
/// عشان كده الفحص ده بيسأل عن الاتنين: فيه عطل؟ وكمان — طابورها فيه كام
/// جوب مستني؟ المكنة اللي عندها شغل مكوّم بتستنى دورها. النتيجة إن في أي
/// لحظة مفيش متلزم لمكنة غير قطعة أو اتنين، والباقي لسه في إيدينا ينفع
/// يروح لغيرها.
///
/// ولاحظ: الجوب اللي **فعلًا** دخل طابور ويندوز بيفضل مكانه — مابنلغيهوش
/// ومابنكررهوش. أول ما حد يحط ورق، هو بيكمّل والمكنة بترجع تسحب لوحدها
/// من غير ما حد يعمل حاجة.
/// </summary>
public interface IPrinterHealth
{
    Task<PrinterHealth> CheckAsync(string printerName, CancellationToken cancellationToken = default);
}

/// <summary>
/// بيقول "كله تمام" دايمًا.
///
/// موجود عشان الأماكن اللي مافيهاش فحص حقيقي (تستات، أو جهاز WMI مش
/// شغالة عليه) تشتغل بنفس السلوك القديم بالظبط بدل ما تقع.
/// </summary>
public sealed class AlwaysFinePrinterHealth : IPrinterHealth
{
    public Task<PrinterHealth> CheckAsync(
        string printerName,
        CancellationToken cancellationToken = default)
        => Task.FromResult(PrinterHealth.Fine);
}
