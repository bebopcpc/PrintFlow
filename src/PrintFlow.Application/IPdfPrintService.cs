using PrintFlow.Domain;

namespace PrintFlow.Application;

public interface IPdfPrintService
{
    /// <summary>
    /// بيبعت أمر طباعة واحد ويرجّع النتيجة: السطر العربي اللي بيتعرض في
    /// اللوج + تصنيف الموزّع بيبني عليه قراره.
    ///
    /// كان بيرجّع نص بس. النص لوحده مكانش بيكفي لما التوزيع بقى حي:
    /// الموزّع محتاج يعرف الفرق بين "فشلت قبل ما ورق يتحرك" (آمن ننقلها
    /// لمكنة تانية) و"اتبعتت وبعدين وقفت" (ممنوع نكررها عشان ماتطلعش
    /// مرتين). شوف <see cref="PrintOutcome"/>.
    ///
    /// غير متزامن بجد — مش Task.Run ملفوفة حوالين انتظار متزامن.
    /// </summary>
    Task<PrintOutcome> PrintAsync(PrintJob job, CancellationToken cancellationToken = default);

    /// <summary>
    /// نفس الطباعة، بس بتبلّغ عن كل دفعة **وهي ماشية**.
    ///
    /// ═══ ليه موجودة ═══
    ///
    /// الأوردر الكبير بيتبعت على دفعات (شوف <see cref="PrintChunking"/>).
    /// من غيرها، النتيجة الوحيدة بتوصل **بعد آخر دفعة** — فالبار بيفضل على
    /// صفر عشر دقايق وبعدين يقفز ١٠٠٪ مرة واحدة.
    ///
    /// واللي واقف على المكنة بيفتكر البرنامج واقف، فيدوس «إيقاف فوري».
    /// وساعتها الطابعات بتفضل تطلّع اللي في ذاكرتها وتقف في أوقات مختلفة —
    /// ودي بالظبط شكوى «وقفت عند الورقة ٤٠».
    ///
    /// ═══ ليه ميثود تانية بجسم افتراضي مش براميتر زيادة ═══
    ///
    /// أول محاولة كانت إضافة براميتر اختياري للميثود اللي فوق. ده كسر
    /// **ستة ملفات تست** فيها نسخ مزيفة من الواجهة دي: البراميتر الاختياري
    /// بيسهّل على اللي **بينده** الدالة، مش على اللي **بينفّذها**.
    ///
    /// الجسم الافتراضي هنا بيحل ده: أي حاجة منفّذة الواجهة القديمة بتفضل
    /// شغّالة زي ما هي وبتاخد السلوك القديم (من غير تبليغ)، والخدمة
    /// الحقيقية بس هي اللي بتكتب فوقه.
    ///
    /// ⚠ ومن غير قيم افتراضية للبراميترات هنا عن قصد — لو كانت موجودة،
    /// نداء زي <c>PrintAsync(job, token)</c> كان هيبقى غامض بين الاتنين.
    /// </summary>
    /// <param name="onCopiesDelivered">
    /// بيتنده بعد كل دفعة بعدد النسخ اللي اتسلّمت فيها.
    /// **بيتنده من ثريد خلفي** — اللي بيستقبله مسؤول عن نقله لثريد الواجهة.
    /// </param>
    Task<PrintOutcome> PrintAsync(
        PrintJob job,
        CancellationToken cancellationToken,
        Action<int>? onCopiesDelivered)
        => PrintAsync(job, cancellationToken);
}